"""DevRel App Documentation Generator — produces .docx files from JSON config.

Usage:
    python -m devrel_client.doc_generator --config app_doc_config.json --output app_documentation.docx

Requires:
    pip install python-docx
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any


def generate_docx(config: dict[str, Any], output_path: str | Path) -> Path:
    """Generate a Word document from an app configuration dict.

    Args:
        config: App metadata dict with keys: app_name, author, date,
            description, architecture, model_card, kpis, usage, troubleshooting.
        output_path: Where to write the .docx file.

    Returns:
        Path to the generated .docx file.
    """
    try:
        from docx import Document  # type: ignore[import-untyped]
        from docx.enum.text import WD_ALIGN_PARAGRAPH  # type: ignore[import-untyped]
        from docx.shared import Inches, Pt  # type: ignore[import-untyped]
    except ImportError:
        print("[error] python-docx not installed. Run:  pip install python-docx")
        sys.exit(1)

    doc = Document()
    output_path = Path(output_path)

    app_name = config.get("app_name", "DevRel Application")
    author = config.get("author", "DevRel App Builder")
    date_str = config.get("date", datetime.now().strftime("%Y-%m-%d"))
    description = config.get("description", "")

    # ── Title Page ──────────────────────────────────────────────────────
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(app_name)
    run.bold = True
    run.font.size = Pt(28)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("Application Documentation")
    run.font.size = Pt(16)

    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    meta.add_run(f"\n\nAuthor: {author}\nDate: {date_str}\n")
    meta.add_run("Generated by DevRel App Builder")

    doc.add_page_break()

    # ── Table of Contents (placeholder) ─────────────────────────────────
    doc.add_heading("Table of Contents", level=1)
    toc_items = [
        "1. Architecture Overview",
        "2. System Diagram",
        "3. Model Card",
        "4. Setup & Installation",
        "5. Usage Guide",
        "6. KPI Summary",
        "7. Troubleshooting",
        "8. Appendix",
    ]
    for item in toc_items:
        doc.add_paragraph(item, style="List Number")

    doc.add_page_break()

    # ── 1. Architecture Overview ────────────────────────────────────────
    doc.add_heading("1. Architecture Overview", level=1)
    doc.add_paragraph(description)

    arch = config.get("architecture", {})
    components = arch.get("components", [])
    if components:
        doc.add_heading("Components", level=2)
        table = doc.add_table(rows=1, cols=3)
        table.style = "Light Grid Accent 1"
        hdr = table.rows[0].cells
        hdr[0].text = "Component"
        hdr[1].text = "File"
        hdr[2].text = "Description"
        for comp in components:
            row = table.add_row().cells
            row[0].text = comp.get("name", "")
            row[1].text = comp.get("file", "")
            row[2].text = comp.get("description", "")

    # ── 2. System Diagram ───────────────────────────────────────────────
    doc.add_heading("2. System Diagram", level=1)
    diagram = arch.get("diagram", "Input -> Model -> Output")
    p = doc.add_paragraph()
    run = p.add_run(diagram)
    run.font.size = Pt(10)
    run.font.name = "Consolas"

    # ── 3. Model Card ───────────────────────────────────────────────────
    doc.add_heading("3. Model Card", level=1)
    model_card = config.get("model_card", {})
    if model_card:
        table = doc.add_table(rows=0, cols=2)
        table.style = "Light Grid Accent 1"
        for key, value in model_card.items():
            row = table.add_row().cells
            row[0].text = key.replace("_", " ").title()
            row[1].text = str(value)

    # ── 4. Setup & Installation ─────────────────────────────────────────
    doc.add_heading("4. Setup & Installation", level=1)
    usage = config.get("usage", {})
    setup = usage.get("setup", ".\\run.ps1")
    doc.add_paragraph("Prerequisites:", style="List Bullet")
    doc.add_paragraph("Python 3.10+", style="List Bullet 2")
    doc.add_paragraph("DevRel server installed (see DevRel repo)", style="List Bullet 2")
    doc.add_paragraph("QAIRT SDK (for real-mode inference)", style="List Bullet 2")

    doc.add_heading("Setup Command", level=2)
    doc.add_paragraph(setup, style="No Spacing")

    # ── 5. Usage Guide ──────────────────────────────────────────────────
    doc.add_heading("5. Usage Guide", level=1)
    run_cmd = usage.get("run", ".venv\\Scripts\\python.exe app.py")
    doc.add_paragraph("Run the application:")
    doc.add_paragraph(run_cmd, style="No Spacing")

    deploy_cmd = usage.get("deploy", "")
    if deploy_cmd:
        doc.add_heading("Deployment", level=2)
        doc.add_paragraph(deploy_cmd, style="No Spacing")

    # ── 6. KPI Summary ──────────────────────────────────────────────────
    doc.add_heading("6. KPI Summary", level=1)
    kpis = config.get("kpis", {})
    if kpis:
        table = doc.add_table(rows=1, cols=4)
        table.style = "Light Grid Accent 1"
        hdr = table.rows[0].cells
        hdr[0].text = "Metric"
        hdr[1].text = "CPU"
        hdr[2].text = "GPU (Adreno)"
        hdr[3].text = "NPU (HTP)"

        metrics = ["latency_ms", "throughput_fps", "power_mw"]
        labels = ["Latency (ms)", "Throughput (FPS)", "Power (mW)"]

        for label, metric in zip(labels, metrics):
            row = table.add_row().cells
            row[0].text = label
            row[1].text = str(kpis.get("cpu", {}).get(metric, "N/A"))
            row[2].text = str(kpis.get("gpu", {}).get(metric, "N/A"))
            row[3].text = str(kpis.get("npu", {}).get(metric, "N/A"))

    doc.add_paragraph()
    doc.add_paragraph(
        "Note: GPU estimates use Adreno active power (~8 W). "
        "NPU estimates use HTP active power (~4.5 W). "
        "CPU estimates derived from process CPU utilization vs package TDP."
    )

    # ── 7. Troubleshooting ──────────────────────────────────────────────
    doc.add_heading("7. Troubleshooting", level=1)
    troubleshooting = config.get("troubleshooting", [])
    if troubleshooting:
        table = doc.add_table(rows=1, cols=2)
        table.style = "Light Grid Accent 1"
        hdr = table.rows[0].cells
        hdr[0].text = "Symptom"
        hdr[1].text = "Fix"
        for item in troubleshooting:
            row = table.add_row().cells
            row[0].text = item.get("symptom", "")
            row[1].text = item.get("fix", "")
    else:
        doc.add_paragraph("No known issues. Run `devrel doctor` to diagnose problems.")

    # ── 8. Appendix ─────────────────────────────────────────────────────
    doc.add_heading("8. Appendix", level=1)

    doc.add_heading("Hardware Specs", level=2)
    hw = config.get("hardware", {})
    if hw:
        for key, value in hw.items():
            doc.add_paragraph(f"{key}: {value}", style="List Bullet")
    else:
        doc.add_paragraph(
            "Run `devrel detect` or `mcp__devrel__hardware_detect` "
            "to populate hardware specifications."
        )

    doc.add_heading("Generated by", level=2)
    doc.add_paragraph(
        f"DevRel App Builder | {date_str} | "
        "https://github.qualcomm.com/pavanr/devrelAgent"
    )

    # ── Save ────────────────────────────────────────────────────────────
    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(output_path))
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate .docx documentation from a DevRel app config JSON."
    )
    parser.add_argument(
        "--config", required=True,
        help="Path to app_doc_config.json",
    )
    parser.add_argument(
        "--output", default="app_documentation.docx",
        help="Output .docx path (default: app_documentation.docx)",
    )
    args = parser.parse_args()

    config_path = Path(args.config)
    if not config_path.exists():
        print(f"[error] Config file not found: {config_path}")
        sys.exit(1)

    config = json.loads(config_path.read_text(encoding="utf-8"))
    out = generate_docx(config, args.output)
    print(f"Generated: {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
